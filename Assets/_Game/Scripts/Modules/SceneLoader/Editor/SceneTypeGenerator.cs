using UnityEngine;
using System.IO;
using System.Linq;
using System.Text;

#if UNITY_EDITOR
using UnityEditor;

namespace Modules.SceneLoader.Editor
{
    [InitializeOnLoad]
    public class SceneTypeGenerator : AssetModificationProcessor
    {
        private static string ENUM_PATH => GetEnumFilePath();
        private static bool _isInitialized = false;

        static SceneTypeGenerator()
        {
            if (!_isInitialized)
            {
                _isInitialized = true;
                EditorApplication.delayCall += Initialize;
            }
        }

        private static void Initialize()
        {
            GenerateSceneTypeEnum();

            EditorBuildSettings.sceneListChanged += OnSceneListChanged;
            EditorApplication.projectChanged += OnProjectChanged;
        }

        private static void OnProjectChanged()
        {
            if (!File.Exists(ENUM_PATH))
            {
                GenerateSceneTypeEnum();
            }
        }

        private static void OnSceneListChanged()
        {
            GenerateSceneTypeEnum();
        }

        public static string[] OnWillSaveAssets(string[] paths)
        {
            GenerateSceneTypeEnum();
            return paths;
        }

        [MenuItem("Modules/Generate SceneType")]
        private static void GenerateSceneTypeEnum()
        {
            try
            {
                var scenes = EditorBuildSettings.scenes
                    .Where(scene => scene.enabled)
                    .Select(scene => Path.GetFileNameWithoutExtension(scene.path))
                    .Where(name => !string.IsNullOrEmpty(name))
                    .Distinct()
                    .ToArray();

                string enumCode = GenerateEnumCode(scenes);
                
                string directory = Path.GetDirectoryName(ENUM_PATH);
                if (!Directory.Exists(directory))
                {
                    Directory.CreateDirectory(directory);
                }

                string currentCode = File.Exists(ENUM_PATH) ? File.ReadAllText(ENUM_PATH) : "";

                if (enumCode != currentCode)
                {
                    File.WriteAllText(ENUM_PATH, enumCode, Encoding.UTF8);
                    Debug.Log($"✅ SceneType enum generated with {scenes.Length} scenes at path: {ENUM_PATH}");
                }
            }
            catch (System.Exception e)
            {
                Debug.LogError($"❌ SceneType generation failed: {e.Message}");
            }
        }

        private static string GetEnumFilePath()
        {
            var currentScriptPath = GetCurrentScriptPath();
            
            if (string.IsNullOrEmpty(currentScriptPath))
            {
                return Path.Combine(Application.dataPath, "AUTO-GENERATED", "SceneType.cs");
            }

            var scriptDirectory = Path.GetDirectoryName(currentScriptPath);
            var parentDirectory = Path.GetDirectoryName(scriptDirectory);
            var autoGeneratedPath = Path.Combine(parentDirectory, "AUTO-GENERATED", "SceneType.cs");
            
            return autoGeneratedPath;
        }

        private static string GetCurrentScriptPath()
        {
            var scriptType = typeof(SceneTypeGenerator);
            
            var guids = AssetDatabase.FindAssets($"t:Script {scriptType.Name}");
            if (guids.Length <= 0) return null;
            
            var assetPath = AssetDatabase.GUIDToAssetPath(guids[0]);
            var fullPath = Path.Combine(Directory.GetCurrentDirectory(), assetPath);
            
            return Path.GetFullPath(fullPath);
        }

        private static string GenerateEnumCode(string[] sceneNames)
        {
            var sb = new StringBuilder();
            sb.AppendLine("// AUTO-GENERATED FILE - DO NOT EDIT MANUALLY");
            sb.AppendLine("// Generated automatically from Build Settings");
            sb.AppendLine("// Any manual changes will be overwritten");
            sb.AppendLine("");
            sb.AppendLine("public enum SceneType");
            sb.AppendLine("{");

            if (sceneNames.Length == 0)
            {
                sb.AppendLine("    None = 0");
            }
            else
            {
                for (int i = 0; i < sceneNames.Length; i++)
                {
                    string validName = MakeValidEnumName(sceneNames[i]);
                    sb.AppendLine($"    {validName} = {i},");
                }
            }
            
            sb.AppendLine("}");
            
            return sb.ToString();
        }

        private static string MakeValidEnumName(string sceneName)
        {
            var validName = System.Text.RegularExpressions.Regex.Replace(sceneName, @"[^a-zA-Z0-9_]", "_");
            if (char.IsDigit(validName[0])) validName = "_" + validName;
            
            return validName;
        }
    }
}
#endif